import { test, expect } from '@playwright/test'

for (const lang of ['zh', 'en']) {
  test('repository update touches only its repository and preserves the other diff and search (' + lang + ')', async ({ page }) => {
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/?lang=' + lang)
    const surface = page.locator('#review-surface')
    const scope = surface.getByRole('combobox', { name: lang === 'zh' ? '审查范围' : 'Review scope' })
    await scope.selectOption('uncommitted')
    const core = surface.getByRole('region', { name: 'core', exact: true })
    const web = surface.getByRole('region', { name: 'web', exact: true })
    await core.getByRole('button', { name: /service\.ts$/ }).click()
    await web.getByRole('button', { name: /service\.ts$/ }).click()
    const coreDiff = core.locator('[data-diff-layout]')
    const webDiff = web.locator('[data-diff-layout]')
    await expect(coreDiff).toContainText('return validate(input)')
    await expect(webDiff).toContainText('return validate(input)')
    await webDiff.getByRole('button', { name: lang === 'zh' ? '搜索' : 'Search', exact: true }).click()
    await webDiff.getByRole('searchbox').fill('validate')
    const before = await page.evaluate(() => window.fixture.gitRequests())
    await page.evaluate(() => {
      window.fixture.updateGitText('export function review(input) {\n  return updatedCore(input)\n}\n', 'D:/fixture/core')
      window.fixture.updateGitFiles('D:/fixture/core', ['service.ts', 'added.ts'])
    })
    const update = core.getByRole('button', { name: lang === 'zh' ? '更新 core' : 'Update core', exact: true })
    // The new button sits next to the repository title, before the right-side actions.
    expect(await update.evaluate(button => button.previousElementSibling?.getAttribute('aria-expanded'))).toBe('true')
    await update.click()
    await expect(coreDiff).toContainText('return updatedCore(input)')
    await expect(coreDiff).toContainText('return input')
    await expect(core.getByRole('button', { name: /added\.ts$/ })).toBeVisible()
    await expect(core.getByText(lang === 'zh' ? '2 个文件' : '2 files', { exact: true })).toBeVisible()
    await expect(webDiff).toContainText('return validate(input)')
    await expect(webDiff.getByRole('searchbox')).toHaveValue('validate')
    const after = await page.evaluate(() => window.fixture.gitRequests())
    expect(after.lists.slice(before.lists.length)).toEqual([{ mode: 'uncommitted', repository: 'D:/fixture/core' }])
    expect(after.diffs.slice(before.diffs.length).map(request => request.repository)).toEqual(['D:/fixture/core'])
    await expect(scope).toHaveValue('uncommitted')
    const repository = surface.getByRole('combobox', { name: lang === 'zh' ? '仓库' : 'Repository' })
    await expect(repository).toHaveValue('*')
    await page.getByRole('button', { name: '400px', exact: true }).click()
    await expect(update).toBeVisible()
    await expect(webDiff.getByRole('searchbox')).toHaveValue('validate')
    await page.screenshot({ path: test.info().outputPath('repository-update-' + lang + '.png'), fullPage: true })
    expect(errors).toEqual([])
  })
}

test('repository update failure preserves the list, supports retry and removes an empty group without touching others', async ({ page }) => {
  await page.goto('/')
  const surface = page.locator('#review-surface')
  await surface.getByRole('combobox', { name: '审查范围' }).selectOption('uncommitted')
  const core = surface.getByRole('region', { name: 'core', exact: true })
  const web = surface.getByRole('region', { name: 'web', exact: true })
  await core.getByRole('button', { name: /service\.ts$/ }).click()
  const diff = core.locator('[data-diff-layout]')
  await expect(diff).toContainText('validate(input)')
  await page.evaluate(() => window.fixture.failGitUpdate('D:/fixture/core', true))
  const update = core.getByRole('button', { name: '更新 core', exact: true })
  await update.click()
  await expect(core.getByRole('alert')).toContainText('Fixture repository unavailable')
  await expect(diff).toContainText('validate(input)')
  await expect(update).toBeEnabled()
  await expect(web.getByRole('button', { name: /service\.ts$/ })).toBeVisible()
  await page.evaluate(() => {
    window.fixture.failGitUpdate('D:/fixture/core', false)
    window.fixture.updateGitFiles('D:/fixture/core', [])
  })
  await update.click()
  await expect(core).toHaveCount(0)
  await expect(web.getByRole('button', { name: /service\.ts$/ })).toBeVisible()
  // A full refresh still works and can rediscover a repository after its changes return.
  await page.evaluate(() => window.fixture.updateGitFiles('D:/fixture/core', ['service.ts']))
  await surface.getByRole('button', { name: '更新', exact: true }).click()
  await expect(core.getByRole('button', { name: '更新 core', exact: true })).toBeEnabled()
})

test('pending repository update is disabled and a late response cannot overwrite a new scope', async ({ page }) => {
  await page.goto('/')
  const surface = page.locator('#review-surface')
  const scope = surface.getByRole('combobox', { name: '审查范围' })
  await scope.selectOption('uncommitted')
  const core = surface.getByRole('region', { name: 'core', exact: true })
  const update = core.getByRole('button', { name: '更新 core', exact: true })
  await expect(update).toBeEnabled()
  await page.evaluate(() => {
    window.fixture.updateGitFiles('D:/fixture/core', ['stale-only.ts'])
    window.fixture.holdGitUpdate('D:/fixture/core')
  })
  await update.click()
  await expect(update).toBeDisabled()
  await expect(update).toHaveText('更新中…')
  await page.evaluate(() => window.fixture.updateGitFiles('D:/fixture/core', ['service.ts']))
  await scope.selectOption('unstaged')
  await expect(core.getByRole('button', { name: /service\.ts$/ })).toBeVisible()
  await page.evaluate(async () => {
    window.fixture.releaseGitUpdate()
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  })
  await expect(core.getByRole('button', { name: /stale-only\.ts$/ })).toHaveCount(0)
  await expect(scope).toHaveValue('unstaged')
  await expect(update).toBeEnabled()
})
