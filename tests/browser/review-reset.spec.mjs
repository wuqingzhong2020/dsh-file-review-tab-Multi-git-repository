import { test, expect } from '@playwright/test'
const key = 'dsh-file-review-tab-multi-git-repository:review-state:browser-fixture'
for (const lang of ['zh', 'en']) {
  test('session reset cancellation, complete clearing, stable numbering and preserved history (' + lang + ')', async ({ page }) => {
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/?lang=' + lang)
    const surface = page.locator('#review-surface')
    const reset = surface.getByRole('button', { name: lang === 'zh' ? '重置' : 'Reset', exact: true })
    await expect(reset).toBeEnabled()
    await expect(page.locator('#review-native-title small')).toHaveText('2')
    const before = await page.evaluate(key => localStorage.getItem(key), key)
    await reset.click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toContainText(lang === 'zh' ? '无法撤销' : 'cannot be undone')
    await expect(dialog).toContainText(lang === 'zh' ? '会话对话历史' : 'conversation history')
    await page.keyboard.press('Escape')
    expect(await page.evaluate(key => localStorage.getItem(key), key)).toBe(before)
    await expect(surface.getByText('service.ts', { exact: true }).first()).toBeVisible()
    // Freeze old opinions in the real input-reference codec before resetting.
    const dock = page.locator('[data-review-comments-dock]')
    await dock.locator('summary').click()
    await dock.getByRole('button', { name: lang === 'zh' ? '随输入发送' : 'Send with input' }).click()
    await reset.click()
    await dialog.getByRole('button', { name: lang === 'zh' ? '确认重置' : 'Confirm reset', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('#review-native-title small')).toHaveCount(0)
    await expect(surface.getByText('service.ts', { exact: true })).toHaveCount(0)
    await expect(page.locator('[data-review-comments-dock]')).toHaveCount(0)
    const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)
    expect(saved.reset.boundarySeq).toBe(4)
    expect(JSON.parse(saved.slices.comments).comments).toEqual([])
    expect(JSON.parse(saved.slices.discussions).records).toEqual([])
    expect(JSON.parse(saved.slices.confirmations).confirmed).toEqual([])
    const expired = await page.evaluate(async () => {
      const input = window.fixture.inputState.getSnapshot()
      try { await window.fixture.source().codec.serialize(input.occurrences[0].ref, new AbortController().signal); return null }
      catch (cause) { return cause.message }
    })
    expect(expired).toMatch(/expired|reset/)
    await expect(page.locator('[data-input-prose]')).toContainText(lang === 'zh' ? '请保持现有接口。' : 'Keep the existing interface.')
    await expect(page.locator('[data-input-attachment]')).toBeVisible()
    await page.evaluate(() => window.__reviewResetFixture.change())
    await expect(surface.getByText(lang === 'zh' ? '第 1 轮' : 'Turn 1', { exact: true })).toBeVisible()
    await expect(surface.getByText('service.ts', { exact: true })).toHaveCount(1)
    await expect(page.locator('#review-native-title small')).toHaveText('1')
    await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)).reset.baseHostTurn, key)).toBe(2)
    await page.reload()
    await expect(reset).toBeEnabled()
    expect((await page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)).generation).toBe(saved.generation)
    await page.getByRole('button', { name: 'Messages', exact: true }).click()
    await expect(page.locator('[data-review-packet]')).toBeVisible()
    await expect(page.locator('[data-host-attachment]')).toBeVisible()
    const oldCard = page.locator('#historical-file-card')
    await expect(oldCard.getByText('service.ts', { exact: true })).toBeVisible()
    await expect(oldCard.getByRole('button', { name: lang === 'zh' ? '撤销' : 'Undo', exact: true })).toBeDisabled()
    await oldCard.getByRole('button', { name: lang === 'zh' ? '审查所有产出文件' : 'Review all produced files' }).click()
    await expect(oldCard.getByRole('alert')).toContainText(lang === 'zh' ? '重置' : 'reset')
    expect(await page.evaluate(() => window.fixture.applyPaths())).toEqual([])
    expect(errors).toEqual([])
  })
}
test('busy or host-queued conversations cannot reset; Git comparison has no reset button', async ({ page }) => {
  await page.goto('/')
  const surface = page.locator('#review-surface')
  const reset = surface.getByRole('button', { name: '重置', exact: true })
  await expect(reset).toBeEnabled()
  await page.evaluate(() => window.__reviewResetFixture.busy(true))
  await expect(reset).toBeDisabled()
  await page.evaluate(() => { window.__reviewResetFixture.busy(false); window.__reviewResetFixture.queued(true) })
  await expect(reset).toBeDisabled()
  await page.evaluate(() => window.__reviewResetFixture.queued(false))
  await expect(reset).toBeEnabled()
  await surface.getByRole('combobox', { name: '审查范围' }).selectOption('uncommitted')
  await expect(reset).toHaveCount(0)
})
test('real same-origin locks exclude operations in another window and storage updates clear both panes', async ({ page, context }) => {
  await page.goto('/')
  const other = await context.newPage()
  await other.goto('/')
  const reset = other.locator('#review-surface').getByRole('button', { name: '重置', exact: true })
  await expect(reset).toBeEnabled()
  await page.evaluate(key => {
    window.activityHold = navigator.locks.request(key + ':activity', { mode: 'shared' }, () =>
      new Promise(resolve => { window.releaseActivity = resolve }))
  }, key)
  await expect.poll(() => page.evaluate(() => typeof window.releaseActivity)).toBe('function')
  await reset.click()
  const dialog = other.getByRole('dialog')
  await dialog.getByRole('button', { name: '确认重置', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('重置未完成')
  expect(await other.evaluate(key => JSON.parse(localStorage.getItem(key)).reset, key)).toBeNull()
  await page.evaluate(() => window.releaseActivity())
  await dialog.getByRole('button', { name: '确认重置', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('#review-surface').getByText('service.ts', { exact: true })).toHaveCount(0)
  await expect(other.locator('#review-surface').getByText('service.ts', { exact: true })).toHaveCount(0)
  await other.close()
})
